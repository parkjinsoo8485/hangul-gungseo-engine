/**
 * Generate a smooth counter-clockwise ellipse starting at 12 o'clock (top = max Y in font coordinates)
 * and closing back at 12 o'clock.
 */
function makeCircle(cx, cy, rx, ry, N = 28) {
    const pts = [];
    for (let i = 0; i <= N; i++) {
        const theta = (2 * Math.PI * i) / N;
        const x = Math.round(cx - rx * Math.sin(theta));
        const y = Math.round(cy + ry * Math.cos(theta));
        pts.push([x, y]);
    }
    return pts;
}

